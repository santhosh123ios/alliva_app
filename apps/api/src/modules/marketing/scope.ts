import type { Prisma } from '@prisma/client';
import { forbidden, notFound } from '../../common/errors';
import type { RequestUser } from '../../common/http';
import type { PrismaService } from '../../prisma/prisma.service';

export type ScopeKind = 'ADMIN' | 'HEAD' | 'STAFF';

export function isPlatformAdmin(actor: RequestUser) {
  return actor.roles.includes('SUPER_ADMIN') || actor.roles.includes('ADMIN');
}

/**
 * The single place that decides what marketing data a caller may read.
 *  - ADMIN  : everything
 *  - HEAD   : records attached to their own team (headUserId = self) and their own money
 *  - STAFF  : only their own records
 * Every query takes its `where` clause from here so authorization lives in the database query, not in the UI.
 */
export class MarketingScope {
  constructor(
    readonly kind: ScopeKind,
    readonly userId: string,
    readonly teamStaffIds: string[] = [],
  ) {}

  get isAdmin() {
    return this.kind === 'ADMIN';
  }
  get isHead() {
    return this.kind === 'HEAD';
  }
  get isStaff() {
    return this.kind === 'STAFF';
  }

  requireAdmin() {
    if (!this.isAdmin) throw forbidden('Only a platform admin can do this');
  }

  leads(): Prisma.MarketingLeadWhereInput {
    if (this.isAdmin) return {};
    return this.isHead ? { headUserId: this.userId } : { marketingUserId: this.userId };
  }

  referrals(): Prisma.MerchantReferralWhereInput {
    if (this.isAdmin) return {};
    return this.isHead ? { headUserId: this.userId } : { marketingUserId: this.userId };
  }

  appointments(): Prisma.MarketingAppointmentWhereInput {
    if (this.isAdmin) return {};
    return this.isHead ? { headUserId: this.userId } : { staffUserId: this.userId };
  }

  visits(): Prisma.MarketingVisitWhereInput {
    if (this.isAdmin) return {};
    return this.isHead ? { headUserId: this.userId } : { staffUserId: this.userId };
  }

  activities(): Prisma.MarketingActivityWhereInput {
    if (this.isAdmin) return {};
    return this.isHead ? { headUserId: this.userId } : { staffUserId: this.userId };
  }

  /** Commissions generated by the people in scope (team view for heads). */
  commissions(): Prisma.CommissionEntryWhereInput {
    if (this.isAdmin) return {};
    return this.isHead ? { headUserId: this.userId } : { beneficiaryUserId: this.userId };
  }

  staffProfiles(): Prisma.MarketingProfileWhereInput {
    if (this.isAdmin) return { kind: 'STAFF' };
    if (this.isHead) return { kind: 'STAFF', parentUserId: this.userId };
    return { kind: 'STAFF', userId: this.userId };
  }

  /** Wallet users a caller can inspect: admin any, head self + own staff are NOT included (head sees only own wallet). */
  walletOwner(requested?: string | null): string {
    if (this.isAdmin) return requested ?? this.userId;
    if (requested && requested !== this.userId) throw notFound('Wallet not found');
    return this.userId;
  }

  canSeeStaff(staffUserId: string) {
    if (this.isAdmin) return true;
    if (this.isStaff) return staffUserId === this.userId;
    return this.teamStaffIds.includes(staffUserId);
  }

  /** Records outside the caller's scope answer 404 (never 403) so record ids cannot be probed. */
  assertStaff(staffUserId: string) {
    if (!this.canSeeStaff(staffUserId)) throw notFound('Not found');
  }
}

export async function resolveScope(prisma: PrismaService, actor: RequestUser): Promise<MarketingScope> {
  if (isPlatformAdmin(actor)) return new MarketingScope('ADMIN', actor.id);
  const profile = await prisma.marketingProfile.findUnique({ where: { userId: actor.id }, select: { kind: true, status: true } });
  if (!profile) throw forbidden('No marketing account');
  if (profile.status !== 'ACTIVE') throw forbidden('This marketing account is not active');
  if (profile.kind === 'HEAD') {
    if (!actor.roles.includes('MARKETING_HEAD')) throw forbidden('Missing role');
    const team = await prisma.marketingProfile.findMany({ where: { parentUserId: actor.id, kind: 'STAFF' }, select: { userId: true } });
    return new MarketingScope('HEAD', actor.id, team.map((row) => row.userId));
  }
  if (!actor.roles.includes('MARKETING_STAFF')) throw forbidden('Missing role');
  return new MarketingScope('STAFF', actor.id);
}

export async function requireAdminScope(prisma: PrismaService, actor: RequestUser) {
  const scope = await resolveScope(prisma, actor);
  scope.requireAdmin();
  return scope;
}
